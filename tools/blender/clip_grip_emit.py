# clip_grip_emit.py - the game's own clip hold of a part, as a designed-grip table (grips.h) for the mod's carry: at
# one clip time, each left finger joint's rotation against its parent and the part's bones against the wrist, in the
# same conventions as grip_solve.py --emit (game frames, Unreal axes). For a part the clip's hand holds well at some
# moment, carried that way wherever the hands' own clip happens to be (the crossbow's new box: the hands clip is not
# playing while the reload holds the weapon clip, so "where the clip's hand has it" put the box 19 units out).
#
#   .\tools\blender-run.ps1 tools\blender\clip_grip_emit.py -- --gun <ws>\exports\bs1\WP_CrossbowMesh.glb
#       --hands-action Crossbow__ReloadCrossbow --gun-action Default__Reload --time 1.70 --part X_AmmoBox
#       --name kCrossbowBoxGrip --emit src\game\bioshock1r\grip_crossbow_box.h
#
# Never launches a game.
import bpy, sys, os, re, argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mathutils import Matrix  # noqa: E402
from game_frames import F, bone_turns, game_frame, glb_bone_order  # noqa: E402

argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
ap = argparse.ArgumentParser(prog="clip_grip_emit.py")
ap.add_argument("--hands", default="")
ap.add_argument("--gun", required=True)
ap.add_argument("--hands-action", required=True)
ap.add_argument("--gun-action", required=True)
ap.add_argument("--time", type=float, required=True)
ap.add_argument("--part", required=True, help="the part's bones, comma-separated")
ap.add_argument("--hand", default="L")
ap.add_argument("--socket", default="R_grip")
ap.add_argument("--name", required=True)
ap.add_argument("--emit", required=True)
args = ap.parse_args(argv)
ws = os.environ.get("BVR_MODEL_WS", os.getcwd())
hands = args.hands or os.path.join(ws, "exports", "bs1", "NEWPlayerHands-all.glb")

for o in list(bpy.data.objects):
    bpy.data.objects.remove(o, do_unlink=True)
for a in list(bpy.data.actions):
    bpy.data.actions.remove(a)


def load(path):
    before, acts0 = set(bpy.data.objects), set(bpy.data.actions)
    bpy.ops.import_scene.gltf(filepath=os.path.abspath(path))
    new = [o for o in bpy.data.objects if o not in before]
    return next(o for o in new if o.type == "ARMATURE"), [a for a in bpy.data.actions if a not in acts0]


ha, hacts = load(hands)
ga, gacts = load(args.gun)
pick = lambda acts, rx: next(a for a in acts if re.search(rx, a.name, re.I))
for arm, act in ((ha, pick(hacts, args.hands_action)), (ga, pick(gacts, args.gun_action))):
    arm.animation_data_create()
    arm.animation_data.action = act
HC, _ = bone_turns(ha, hands)
GC, _ = bone_turns(ga, args.gun)
c = ga.constraints.new("CHILD_OF")
c.target, c.subtarget = ha, args.socket
c.inverse_matrix = HC.get(args.socket, Matrix.Identity(4)).inverted()
scn = bpy.context.scene
# Clip seconds at the scene's own rate (the glTF actions run at it), as reload_pose.py samples them.
fps = scn.render.fps / scn.render.fps_base
scn.frame_set(int(args.time * fps), subframe=(args.time * fps) % 1.0)
bpy.context.view_layer.update()

side = args.hand.upper()
wrist = "Bip01_%s_Hand" % side
order = glb_bone_order(hands)
rows = []
for f in ("Thumb", "Index", "Middle", "Ring", "Pinky"):
    for k in (1, 2, 3):
        b = "kBone_%s_%s%d" % (side, f, k)
        par = ha.pose.bones[b].parent.name
        q = (F @ (game_frame(ha, HC, par).inverted() @ game_frame(ha, HC, b)) @ F).to_quaternion()
        rows.append((b, par, q))
wg = game_frame(ha, HC, wrist)
held = []
for p in [x for x in re.split(r"[ ,]+", args.part) if x]:
    rel = F @ (wg.inverted() @ game_frame(ga, GC, p)) @ F
    held.append((p, rel.to_translation(), rel.to_quaternion()))
with open(args.emit, "w", newline="\r\n") as fh:
    fh.write("#pragma once\n// Generated by tools/blender/clip_grip_emit.py - do not edit by hand. The game's own hold: %s at %.3f s,\n"
             "// the part %s. Each finger joint's rotation against its parent, and the part against the wrist bone (%s),\n"
             "// Unreal axes (x y z w).\n" % (args.hands_action, args.time, args.part, wrist))
    fh.write("#include \"game/bioshock1r/grips.h\"\n\nnamespace bvr::b1r::grips {\n")
    fh.write("inline constexpr GripJoint %s[] = {\n" % args.name)
    for b, p, q in rows:
        fh.write("    {%d, %d, {%.7ff, %.7ff, %.7ff, %.7ff}}, // %s\n" % (order.index(b), order.index(p), q.x, q.y, q.z, q.w, b))
    fh.write("};\ninline constexpr GripPart %sPart[] = {\n" % args.name)
    for n, t, q in held:
        fh.write("    {\"%s\", {%.5ff, %.5ff, %.5ff}, {%.7ff, %.7ff, %.7ff, %.7ff}},\n" % (n, t.x, t.y, t.z, q.x, q.y, q.z, q.w))
    fh.write("};\n} // namespace bvr::b1r::grips\n")
for n, t, q in held:
    print("BVR_CLIPGRIP %s against the wrist: %s (%.2f away)" % (n, [round(x, 2) for x in t], t.length))
print("BVR_CLIPGRIP emitted %d joints, %d part bone(s) -> %s" % (len(rows), len(held), args.emit))
